"""Export pdfminer.six data tables (glyph list, encodings, core-14 metrics) to PHP.

Run with a Python that has pdfminer.six installed:  .venv/bin/python tools/export_data.py
"""
import json
import os
import shutil

import pdfminer
from pdfminer.encodingdb import EncodingDB
from pdfminer.fontmetrics import FONT_METRICS
from pdfminer.glyphlist import glyphname2unicode

ROOT = os.path.join(os.path.dirname(__file__), "..", "resources")


def php_str(s):
    out = "'"
    for ch in s:
        if ch in "\\'":
            out += "\\" + ch
        else:
            out += ch
    return out + "'"


def php(value):
    if isinstance(value, dict):
        return "[" + ",".join(f"{php(k)}=>{php(v)}" for k, v in value.items()) + "]"
    if isinstance(value, (list, tuple)):
        return "[" + ",".join(php(v) for v in value) + "]"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return php_str(value)
    raise TypeError(value)


def write(name, value, comment):
    with open(os.path.join(ROOT, name), "w", encoding="utf-8") as f:
        f.write(f"<?php\n\n// {comment}\n// Generated by tools/export_data.py from pdfminer.six {pdfminer.__version__}.\n\nreturn {php(value)};\n")


write("glyphlist.php", glyphname2unicode, "Adobe Glyph List: glyph name => Unicode text.")
write(
    "encodings.php",
    {name: table for name, table in EncodingDB.encodings.items()},
    "Latin text encodings: code => Unicode text.",
)
write(
    "fontmetrics.php",
    {name: [desc, widths] for name, (desc, widths) in FONT_METRICS.items()},
    "Adobe core fonts: name => [descriptor, char => width]. Adobe AFM license applies.",
)

src = os.path.join(os.path.dirname(pdfminer.__file__), "cmap")
for fn in os.listdir(src):
    if fn.endswith(".json.gz"):
        shutil.copy(os.path.join(src, fn), os.path.join(ROOT, "cmap", fn))
shutil.copy(os.path.join(src, "README.txt"), os.path.join(ROOT, "cmap", "README.txt"))
print("done")
